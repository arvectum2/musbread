#!/usr/bin/env python3
"""True HTTP admin editorial approval -> database queue -> real Next -> Docker public HTTP.

All data is generated by PHPUnit in a disposable in-memory SQLite DB. The
approved snapshot is written to a private ephemeral staging directory on
ArvectumSSD, then compiled by real Next.js in a disposable web tree. The
read-only public Nginx receives six byte-checked files over two Docker nets.
No original museum DB, public host, DNS, approval or media is modified.
"""
from __future__ import annotations
import hashlib,json,os,secrets,shutil,sys,tempfile,time
from datetime import datetime,timezone
from pathlib import Path
from qa_real_laravel_queue_to_static import CMS,WEB,ROOT,execute
from verify_museum_two_contour_docker import test as verify_delivery

NEWS='qa-approved-edition-queue-news'
DRAFT='qa-unapproved-draft-hidden'


def main():
 storage=ROOT/'.local_archive'
 storage.mkdir(mode=0o700,exist_ok=True)
 with tempfile.TemporaryDirectory(prefix='explicit-approval-to-docker-',dir=storage) as tmp:
  root=Path(tmp)
  stage=root/'private-editor-approved-export'
  stage.mkdir(mode=0o700)
  env=dict(os.environ)
  env['MUSBREAD_APPROVAL_QA_OUTPUT_DIR']=str(stage)
  env['NEXT_TELEMETRY_DISABLED']='1'
  # PHPUnit uses its isolated in-memory SQLite DB. The actual protected
  # controller action calls museum:queue-export after writing the approval.
  started=time.perf_counter()
  test_result=execute(['php','artisan','test','tests/Feature/MuseumRealApprovalToQueuedExportTest.php','--compact'],CMS,env,timeout=160)
  if 'passed' not in test_result.lower():
   raise RuntimeError('Real admin approval PHP controller/DB worker test did not pass')
  snapshot=stage/'published.json'
  signed=stage/'snapshot-manifest.json'
  evidence=stage/'approval-observation.json'
  if not all(p.is_file() for p in (snapshot,signed,evidence)):
   raise RuntimeError('Explicit approval did not produce all private stage files')
  observation=json.loads(evidence.read_text())
  approved_at=datetime.fromisoformat(observation['approved_at_utc'])
  if approved_at.tzinfo is None:
   raise RuntimeError('Approval time lacks timezone')
  approved_unix=approved_at.timestamp()
  if (observation['approvals']!=2
      or observation['real_database_jobs_finished']!=1
      or observation['run_status']!='succeeded'):
   raise RuntimeError('Not exactly two real editorial approvals and one successful database job')
  payload=json.loads(snapshot.read_text())
  pub=[a['slug'] for a in payload['entries']]
  if pub!=[NEWS] or any(x.get('slug')==DRAFT for x in payload['entries']):
   raise RuntimeError('Protected admin approval exported an unexpected article or leaked draft')
  event_slugs=[x['slug'] for x in payload['events']]
  if event_slugs!=['qa-approved-queue-event']:
   raise RuntimeError('Actual approved event not in signed CMS export')
  sha=hashlib.sha256(snapshot.read_bytes()).hexdigest()
  manifest=json.loads(signed.read_text())
  if sha!=observation['snapshot_sha256'] or sha!=manifest['files']['published.json']['sha256']:
   raise RuntimeError('Actual editorial approval / worker export integrity mismatch')
  if not (0 <= time.time()-approved_unix < 3600):
   raise RuntimeError('An actual editor approval timestamp is missing or SLA exceeded')
  print('TRUE_ADMIN_HTTP_APPROVAL_TO_DATABASE_QUEUE_PASS '+json.dumps({
   'approvals':2,'real_queue_jobs':1,'snapshot_sha256':sha,
   'drafts_excluded':True,'approval_to_private_export_seconds':round(observation['approval_to_export_seconds'],3)
  },ensure_ascii=False,sort_keys=True),flush=True)

  # Disposable copy: never override tracked Next content or legacy SEO scripts.
  web=root/'isolated-approved-next-build'
  shutil.copytree(WEB,web,ignore=shutil.ignore_patterns('node_modules','.next','out','test-results','playwright-report'))
  (web/'node_modules').symlink_to(WEB/'node_modules',target_is_directory=True)
  package=web/'package.json'
  scripts=json.loads(package.read_text())
  scripts['scripts'].pop('postbuild',None)
  package.write_text(json.dumps(scripts,ensure_ascii=False,indent=2)+'\n')
  shutil.copy2(snapshot,web/'src/data/published.json')
  shutil.copy2(signed,web/'public/snapshot-manifest.json')
  for folder in ['media','documents']:
   if (stage/folder).is_dir():
    shutil.copytree(stage/folder,web/'public'/folder,dirs_exist_ok=True)
  execute(['npm','run','build','--','--webpack'],web,env,timeout=220)
  out=web/'out'
  article=out/'news'/NEWS/'index.html'
  if not article.is_file():
   raise RuntimeError('Approved Laravel news missing from independently built Next site')
  body=article.read_text()
  if (NEWS not in body or 'QA: Новость после настоящего решения редактора' not in body
      or DRAFT in body or 'noindex' not in body
      or (out/'news'/DRAFT/'index.html').exists()):
   raise RuntimeError('Approved content missing or unapproved draft published in static build')
  print('TRUE_EDITORIAL_APPROVAL_TO_NEXT_BUILD_PASS '+json.dumps({
   'approved_news_html_sha256':hashlib.sha256(article.read_bytes()).hexdigest(),
   'draft_404':True,'preview_noindex':True
  },ensure_ascii=False,sort_keys=True),flush=True)

  # Real courier: source export came from the protected HTTP admin approval.
  report=verify_delivery(source_output=out,required_news=f'news/{NEWS}/index.html')
  if not report['queue_built_news_visible_by_HTTP']:
   raise RuntimeError('Actual admin-approved news was not visible via Nginx')
  elapsed=time.time()-approved_unix
  if elapsed<0 or elapsed>=3600:
   raise RuntimeError('The approved article was not visible within 60 minutes')
  total=time.perf_counter()-started
  print('TRUE_ADMIN_APPROVAL_TO_PUBLIC_HTTP_60_MIN_LOCAL_QA_PASS '+json.dumps({
   'approved_at_utc':observation['approved_at_utc'],
   'approved_edition_news':NEWS,
   'approval_to_public_HTTP_seconds':round(elapsed,3),
   'full_QA_wall_seconds':round(total,3),
   'real_admin_HTTP_POST':True,
   'real_database_queue_worker':True,
   'real_next_production_build':True,
   'isolated_docker_public_HTTP':True,
   'real_museum_network_SLA_proven':False,
   'site_and_DNS_untouched':True
  },ensure_ascii=False,sort_keys=True),flush=True)

if __name__=='__main__':
 try: main()
 except Exception as exc:
  print('LOCAL_APPROVAL_SLA_QA_FAILED '+str(exc)[-850:],file=sys.stderr,flush=True)
  raise
