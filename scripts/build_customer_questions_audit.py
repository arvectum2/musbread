 if n<=108:return "2.4.1; 6.1; 7.3"
 if n<=267:return "1.2; 5.3–5.5; 6.1"
 if n<=277:return "1.4; 5.1–5.5; 8.4"
 if n<=295:return "2.4.17; 6.1–6.2"
 if n<=301:return "2.4.2; 6.1; 7.3.1"
 if n<=317:return "2.4.8; 5.1.3; 5.11"
 return "2.4.11–15; 5.1.3; 6.3–6.5"

