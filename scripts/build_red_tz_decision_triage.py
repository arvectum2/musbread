def main():
 with DATA.open(encoding='utf-8-sig',newline='') as f: source=list(csv.DictReader(f,delimiter=';'))
 if len(source)!=325:raise ValueError('Expected all 325 original requirements')
 red=[row for row in source if row['Готовность']=='Нет']
