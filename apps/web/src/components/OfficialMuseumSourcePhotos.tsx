/**
 * Self-hosted original museum image library. The SOURCE URL is provenance only.
 * Old Drupal/muzei-xleb.ru image requests must never appear in new site's HTML;
 * after cutover, all image bytes are served from our static Next.js deployment.
 */
import {localMuseumPhoto,reviewedMuseumPhotoAlt,museumArchivalImageText} from "@/data/museum-photo-assets";
import MuseumAnchor from "@/components/MuseumAnchor";

export type OriginalMuseumPhoto = {url:string;alt?:string};

export default function OfficialMuseumSourcePhotos({photos:items,label,limit=4}:{
  photos:readonly OriginalMuseumPhoto[]|undefined;
  label:string;
  limit?:number;
}){
  const checked=(items||[]).map(item=>({item,src:localMuseumPhoto(item.url)}))
    .filter((p):p is {item:OriginalMuseumPhoto;src:string}=>p.src!==null).slice(0,limit);
  if(checked.length===0)return null;
  return <div className="official-museum-source-photos" aria-label={`Фотографии музея: ${label}`}>
    {checked.map(({item,src},index)=>{
      // Official museum wording takes precedence. Only when missing, use an
      // objective description from actual visual examination (DRAFT/UAT).
      const officialAlt=item.alt?.trim() || "";
      // Preserve real curator-supplied text; only upgrade autogenerated "photo N".
      const numberedPlaceholder=/[—–-]\s*фотографи[яи]\s*\d+\s*$/i.test(officialAlt);
      // TZ-194: an image alt is concise, but the exact historical museum
      // attribution (when longer) stays accessible via the link's name.
      const requiresShortAlt=numberedPlaceholder || officialAlt.length>125
        || /^график\s/i.test(officialAlt);
      const description=(officialAlt && !requiresShortAlt ? officialAlt : reviewedMuseumPhotoAlt(src))
        || officialAlt || label+" — фотография "+(index+1);
      const sourceAttribution=officialAlt.length>125
        ? "Полная музейная атрибуция: "+officialAlt : null;
      const historicalText=museumArchivalImageText(src);
      const accessibleName=["Открыть: "+description,sourceAttribution,
        historicalText ? "Архивное объявление (НЕ действующее расписание): "+historicalText : null]
        .filter(Boolean).join(". ");
      return <MuseumAnchor href={src} key={item.url}
        target="_blank" rel="noopener noreferrer"
        title={sourceAttribution || "Открыть: "+description}
        aria-label={accessibleName}>
        {/* Image bytes, provenance and target URL are unchanged. */}
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img src={src} alt={description}
          loading="lazy" decoding="async" width="420" height="280" />
      </MuseumAnchor>;
    })}
  </div>;
}
