/** Presentation-agnostic visibility rules for the museum guide route.
 *
 * An authoritative source-backed catalogue and its published CMS revision
 * must never appear twice within the same page. Do not alter the originals,
 * CMS entries or their ordering to achieve this.
 */
export type GuideEntryRef = {type:string; slug:string};

export function visibleGuideSectionEntries<T extends GuideEntryRef>(
  currentSlug:string, entries:readonly T[], duplicates:ReadonlySet<string>,
):T[] {
  return entries.filter(entry=>
    !(entry.type==="page" && entry.slug===currentSlug)
    && !duplicates.has(entry.slug));
}

/** A real museum CMS page overrides its official imported reference; a
 * source-backed category is not duplicated by an autogenerated introduction.
 */
export function shouldShowGuideReferenceBody(input:{
  slug:string;
  hasBody:boolean;
  hasCmsPage:boolean;
  sourceProgramsCategory:boolean;
  sourceExhibitionCategory:boolean;
}):boolean {
  if(!input.hasBody)return false;
  if(["museum-contacts","museum-team","museum-cookie"].includes(input.slug))return false;
  if(input.slug==="museum-exposition" && !input.hasCmsPage)return false;
  if(input.sourceProgramsCategory && !input.hasCmsPage)return false;
  if(input.sourceExhibitionCategory && !input.hasCmsPage)return false;
  return true;
}
